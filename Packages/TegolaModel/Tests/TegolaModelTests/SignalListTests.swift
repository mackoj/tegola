import Foundation
import TegolaCatalogue
import TegolaModelTesting
import Testing

@testable import TegolaModel

/// The M4 exit test's stand-in (tasks/plan.md T4.4): the signal list a 200-object shelf gives, written out in plain
/// words. The owner reads `docs/testing/signals-200.md` and says whether they agree on 8 of 10; this test keeps the
/// file in step with the clocks. Run with `RECORD_GOLDEN=1` to rewrite it after a deliberate change.
@Suite struct SignalListTests {
  static let golden = URL(filePath: #filePath)
    .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()  // TegolaModel
    .deletingLastPathComponent().deletingLastPathComponent()  // repo
    .appending(path: "docs/testing/signals-200.md")

  @Test func theShelfHasTwoHundredObjectsAcrossTheFourTypes() throws {
    let shelf = try SignalShelf(catalogue: Harness.catalogue).shelf
    #expect(shelf.objects.count == 200)
    #expect(Set(shelf.objects.values.map(\.typeID)) == Set(Catalogue.enabledInV1))
  }

  @Test func theSignalListMatchesTheGoldenFile() throws {
    var fixture = try SignalShelf(catalogue: Harness.catalogue)
    try fixture.dismissWatchedBatteries(count: 3)
    let list = Self.render(fixture)
    if ProcessInfo.processInfo.environment["RECORD_GOLDEN"] != nil {
      try list.write(to: Self.golden, atomically: true, encoding: .utf8)
    }
    let recorded = try String(contentsOf: Self.golden, encoding: .utf8)
    #expect(recorded == list, "the signal list changed: run with RECORD_GOLDEN=1, then read the diff")
  }

  /// Every signal is something the screens can word: each reason case has a phrase here, and the same cases become
  /// the String Catalog keys in T4.5.
  static func phrase(_ reason: StatusReading.Reason) -> String {
    switch reason {
    case .letGo: "Let go"
    case .overdue: "Overdue: lent and past its due date"
    case .needsDetails: "Needs details"
    case .unconfirmed: "To tidy: not confirmed yet"
    case .lent: "Out: lent, not due yet"
    case .settled: "Nothing to say"
    case .clock(let signal):
      switch signal.reason {
      case .batteryAging(let fitted, let years): "Save battery from \(fitted) is near its usual \(years) years"
      case .batteryPastLifespan(let fitted, let years): "Save battery from \(fitted) is past its usual \(years) years"
      case .checkDue(let since, let every): "Due a look: last checked \(since), worth doing every \(every) years"
      case .codeExpiring(let on): "Code expires \(on.formatted(.iso8601.year().month().day()))"
      case .codeExpired(let on): "Code expired \(on.formatted(.iso8601.year().month().day()))"
      case .windowOpensSoon(let from): "Drinking window opens \(from)"
      case .windowOpen(let from, let to): "Drink it: window \(from)–\(to)"
      case .windowClosing(let to): "Drinking window closes \(to)"
      case .windowPast(let to): "Past its drinking window (\(to))"
      case .serviceDue(let since, let months): "Due a service: last \(since), every \(months) months"
      case .serviceOverdue(let since, let months): "Service overdue: last \(since), every \(months) months"
      }
    }
  }

  static func render(_ fixture: SignalShelf) -> String {
    let shelf = fixture.shelf
    let readings = StatusReading.all(
      shelf: shelf,
      catalogue: fixture.catalogue,
      now: SignalShelf.now,
      calendar: SignalShelf.calendar
    )
    let rows = shelf.objects.values
      .map { object in (object, readings[object.id]!) }
      .sorted { ($0.1.status, $0.0.typeID.rawValue, $0.0.title) < ($1.1.status, $1.0.typeID.rawValue, $1.0.title) }
    let signals = rows.filter { $0.1.isSignal }
    func line(_ object: ShelfObject, _ reading: StatusReading) -> String {
      let year = if case .year(let year) = object.values[.year] { " \(year)" } else { "" }
      let subtype = object.subtype.map { " · \($0)" } ?? ""
      let estimate = if case .clock = reading.reason { " *(estimate)*" } else { "" }
      let dismissed =
        (object.dismissed ?? [:]).isEmpty
        ? "" : " — dismissed: \(object.dismissed!.keys.sorted().joined(separator: ", "))"
      return
        "| \(reading.status.rawValue.uppercased()) | \(object.title) | \(object.typeID.rawValue)\(subtype)\(year) | \(phrase(reading.reason))\(estimate)\(dismissed) |"
    }
    var text = """
      # The M4 signal list (200 objects)

      Generated by `SignalListTests` from `SignalShelf` (`Packages/TegolaModel/Sources/TegolaModelTesting`), read on
      2026-11-01. **The exit test** (page 52, P2): read the signals below and mark each one you agree with. 8 of 10 or
      better passes. Then glance at the rest: anything that should have been a signal and isn't counts against it.

      **Need attention: \(signals.count)** of \(rows.count) objects (clocks and overdue loans, PLAN F15). Three
      save-battery signals at watch were dismissed, as a collector who had seen them would, and are hidden.

      ## Signals

      | Status | Object | Type, subtype, year | Why |
      |---|---|---|---|

      """
    text += signals.map { line($0.0, $0.1) }.joined(separator: "\n")
    text += "\n\n## Everything else\n\n| Status | Object | Type, subtype, year | Why |\n|---|---|---|---|\n"
    text += rows.filter { !$0.1.isSignal }.map { line($0.0, $0.1) }.joined(separator: "\n")
    return text + "\n"
  }
}
